import { CONSOLE_PRICE, DEFAULT_MONTHLY_TREATMENTS, KIT_COST } from "@/lib/economics";

export const US_MED_SPAS_2023 = 10488;
export const HYDRADERMABRASION_SHARE = 0.57;
export const TEAM_QUALIFICATION_SHARE = 0.70;
export const TEAM_SERVICEABILITY_SHARE = 0.40;
export const TEAM_CAPTURE_SHARE = 0.05;
export const TAM_LOCATIONS = Math.round(US_MED_SPAS_2023 * HYDRADERMABRASION_SHARE * TEAM_QUALIFICATION_SHARE);
export const SAM_LOCATIONS = Math.round(TAM_LOCATIONS * TEAM_SERVICEABILITY_SHARE);
export const SOM_LOCATIONS = Math.round(SAM_LOCATIONS * TEAM_CAPTURE_SHARE);
export const ANNUAL_KITS_PER_LOCATION = DEFAULT_MONTHLY_TREATMENTS * 12;
export const ANNUAL_KIT_REVENUE_PER_LOCATION = ANNUAL_KITS_PER_LOCATION * KIT_COST;
export const TAM_EQUIPMENT_POTENTIAL = TAM_LOCATIONS * CONSOLE_PRICE;
export const SAM_EQUIPMENT_POTENTIAL = SAM_LOCATIONS * CONSOLE_PRICE;
export const TAM_ANNUAL_KIT_SCENARIO = TAM_LOCATIONS * ANNUAL_KIT_REVENUE_PER_LOCATION;
export const SAM_ANNUAL_KIT_SCENARIO = SAM_LOCATIONS * ANNUAL_KIT_REVENUE_PER_LOCATION;